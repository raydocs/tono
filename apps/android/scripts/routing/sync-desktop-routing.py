#!/usr/bin/env python3
"""Generate the mobile routing contract from a raydocs/tono desktop checkout.

The desktop owns the lists: apps/windows/crates/tono-core/src/direct_domains.rs
(Home/video/CIDR/protected) and tooling/scripts/sing-box/three-tier-template.json
(explicit domestic/overseas hosts). This script copies them verbatim into
Kotlin and records the desktop commit. `--check` fails when the committed file
differs from what the given checkout would generate.

usage: sync-desktop-routing.py --desktop <checkout> [--check]
"""
import argparse
import json
import pathlib
import re
import subprocess
import sys

REPO = pathlib.Path(__file__).resolve().parents[2]
# rw8/Tono-droid keeps modules under android/; the raydocs/tono export (apps/android) at the root.
_CONTRACT = "routing/src/main/kotlin/com/raydocs/tono/routing/DesktopRoutingContract.kt"
OUT = next((p for p in (REPO / "android" / _CONTRACT, REPO / _CONTRACT) if p.parent.is_dir()), REPO / "android" / _CONTRACT)


def rust_array(source: str, name: str) -> list[str]:
    match = re.search(rf"pub const {name}: (?:\[&str; (\d+)\]|&\[&str\]) = (?:\[|&\[)(.*?)\n?\];", source, re.S)
    if not match:
        sys.exit(f"missing {name}")
    body = match.group(2)
    if name == "CLAUDE_HOME_DOMAINS":
        dedicated = rust_array(source, "DEDICATED_MODEL_API_SUFFIXES")
        body = re.sub(r"DEDICATED_MODEL_API_SUFFIXES\[(\d)\]", lambda m: f'"{dedicated[int(m.group(1))]}"', body)
    body = re.sub(r"//[^\n]*", "", body)
    values = re.findall(r'"([^"]+)"', body)
    if match.group(1) and int(match.group(1)) != len(values):
        sys.exit(f"{name}: declared {match.group(1)} entries, parsed {len(values)}")
    return values


def rust_int_array(source: str, name: str) -> list[int]:
    match = re.search(rf"pub const {name}: \[u16; (\d+)\] = \[(.*?)\];", source, re.S)
    if not match:
        sys.exit(f"missing {name}")
    body = re.sub(r"//[^\n]*", "", match.group(2))
    values = [int(v) for v in re.findall(r"\b(\d+)\b", body)]
    if int(match.group(1)) != len(values):
        sys.exit(f"{name}: declared {match.group(1)} entries, parsed {len(values)}")
    return values


def kotlin_list(name: str, values: list[str]) -> str:
    rows = "\n".join(f'        "{v}",' for v in values)
    return f"    val {name}: List<String> = listOf(\n{rows}\n    )\n"


def kotlin_int_list(name: str, values: list[int]) -> str:
    rows = "\n".join(f"        {v}," for v in values)
    return f"    val {name}: List<Int> = listOf(\n{rows}\n    )\n"


def generate(desktop: pathlib.Path) -> str:
    rust = (desktop / "apps/windows/crates/tono-core/src/direct_domains.rs").read_text()
    template = json.loads((desktop / "tooling/scripts/sing-box/three-tier-template.json").read_text())
    commit = subprocess.run(["git", "-C", str(desktop), "rev-parse", "HEAD"], check=True,
                            capture_output=True, text=True).stdout.strip()
    home = rust_array(rust, "CLAUDE_HOME_DOMAINS")
    video = rust_array(rust, "CLOUD_VIDEO_DOMAINS")
    cidrs = rust_array(rust, "CLAUDE_HOME_IPV4_CIDRS")
    stun_ports = rust_int_array(rust, "STUN_UDP_PORTS")
    encrypted_dns_ports = rust_int_array(rust, "ENCRYPTED_DNS_PORTS")
    public_stun_suffixes = rust_array(rust, "PUBLIC_STUN_SUFFIXES")
    mobile_home_aux = rust_array(rust, "MOBILE_HOME_AUX_SUFFIXES")
    x_cloud_suffixes = rust_array(rust, "X_CLOUD_SUFFIXES")
    overseas_udp_cidrs = rust_array(rust, "OVERSEAS_UDP_REJECT_IPV4_CIDRS")
    overseas_udp_v6_cidrs = rust_array(rust, "OVERSEAS_UDP_REJECT_IPV6_CIDRS")
    protected = rust_array(rust, "PROTECTED_DIRECT_SUFFIXES")
    assert len(home) == 194 and len(video) == 21, (len(home), len(video))
    assert len(stun_ports) == 8 and len(encrypted_dns_ports) == 1, (len(stun_ports), len(encrypted_dns_ports))
    assert len(public_stun_suffixes) == 5 and len(mobile_home_aux) == 44 and len(x_cloud_suffixes) == 10, (len(public_stun_suffixes), len(mobile_home_aux), len(x_cloud_suffixes))
    assert len(overseas_udp_cidrs) == 33 and len(overseas_udp_v6_cidrs) == 21, (len(overseas_udp_cidrs), len(overseas_udp_v6_cidrs))
    assert template["version"] == 2
    return (
        "// GENERATED by scripts/routing/sync-desktop-routing.py. Do not edit.\n"
        f"// Source: raydocs/tono@{commit}\n"
        "//   apps/windows/crates/tono-core/src/direct_domains.rs\n"
        "//   tooling/scripts/sing-box/three-tier-template.json (version 2)\n"
        "package com.raydocs.tono.routing\n\n"
        "object DesktopRoutingContract {\n"
        f'    const val SOURCE_COMMIT: String = "{commit}"\n\n'
        "    /** Cloud-only video sites; they precede the broad Home parents (e.g. googleapis.com). */\n"
        + kotlin_list("CLOUD_VIDEO_SUFFIXES", video) + "\n"
        "    /** Owner-approved AI / named Home suffixes, routed to the assigned residential exit. */\n"
        + kotlin_list("HOME_SUFFIXES", home) + "\n"
        "    /** Claude / AI auxiliary support, fingerprinting, anti-fraud, captcha, Apple OAuth, telemetry, and SSO suffixes routed through the Home tier on mobile. */\n"
        + kotlin_list("MOBILE_HOME_AUX_SUFFIXES", mobile_home_aux) + "\n"
        "    /** X (Twitter) full domain suffixes routed through the Cloud exit on mobile after Home rules (so grok.x.com stays on Home). */\n"
        + kotlin_list("X_CLOUD_SUFFIXES", x_cloud_suffixes) + "\n"
        "    /** Anthropic's own IPv4 range for raw-IP dials. */\n"
        + kotlin_list("HOME_IPV4_CIDRS", cidrs) + "\n"
        "    /** Google WebRTC STUN UDP ports rejected across routing modes so raw-IP STUN probes cannot leak the physical egress IP. */\n"
        + kotlin_int_list("STUN_UDP_PORTS", stun_ports) + "\n"
        "    /** Encrypted DNS (DoT/DoQ) port rejected in TUN so apps fall back to port-53 DNS where sing-box serves FakeIP. */\n"
        + kotlin_int_list("ENCRYPTED_DNS_PORTS", encrypted_dns_ports) + "\n"
        "    /** Third-party public STUN/TURN suffixes whose UDP/ICMP is rejected across routing modes and whose TCP/DNS stays off DIRECT. */\n"
        + kotlin_list("PUBLIC_STUN_SUFFIXES", public_stun_suffixes) + "\n"
        "    /** Overseas STUN, public DNS, CDN, AI and messaging IPv4 ranges whose UDP/ICMP is rejected while domestic UDP stays direct. */\n"
        + kotlin_list("OVERSEAS_UDP_REJECT_IPV4_CIDRS", overseas_udp_cidrs) + "\n"
        "    /** Overseas STUN, public DNS, CDN, AI and messaging IPv6 ranges whose UDP/ICMP is rejected on dual-stack networks while domestic IPv6 stays direct. */\n"
        + kotlin_list("OVERSEAS_UDP_REJECT_IPV6_CIDRS", overseas_udp_v6_cidrs) + "\n"
        "    /** Hosts that no rule may ever send DIRECT. */\n"
        + kotlin_list("PROTECTED_DIRECT_SUFFIXES", protected) + "\n"
        "    /** Three-tier explicit domestic exact hosts (DIRECT). */\n"
        + kotlin_list("DOMESTIC_EXACT", template["domestic_full"]) + "\n"
        "    /** Three-tier explicit overseas exact hosts (cloud exit). */\n"
        + kotlin_list("OVERSEAS_EXACT", template["overseas_full"])
        + "}\n"
    )


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--desktop", required=True, type=pathlib.Path)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    text = generate(args.desktop)
    if args.check:
        # The lists must match; the recorded source commit may be older than the checkout.
        def lists(t: str) -> str:
            return re.sub(r"(raydocs/tono@|SOURCE_COMMIT: String = \")[0-9a-f]{40}", r"\1<commit>", t)
        if not OUT.exists() or lists(OUT.read_text()) != lists(text):
            sys.exit(f"{OUT.relative_to(REPO)} is stale; rerun without --check")
        print("routing contract matches desktop checkout")
        return
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(REPO)}")


if __name__ == "__main__":
    main()
