#!/usr/bin/env python3
"""Writes the Tono state symbols (custom SF Symbols, template v4) for the Control Center switch.

Geometry is the desktop state glyph (`apps/windows/app/scripts/generate-tono-icons.py`
`draw_state_glyph`, 18-unit grid): a filled half sun over the horizon for "on" (connected), an open
arch for "off" (standby, no protection claim), plus the horizon bar and one reflection. Every weight
and scale uses the same outline; the symbols only appear at Control Center size.

Run from the repository root: python3 apps/ios/tools/generate-control-symbols.py
"""
from pathlib import Path

ASSETS = Path("apps/ios/App/Resources/Assets.xcassets")
UNIT = 6.0  # symbol units per desktop grid unit (glyph height ≈ the cap height, 70 units)
X0, Y0 = 1.5, 15.3  # desktop grid point placed at the left margin / baseline
WIDTH = 15 * UNIT


def p(x: float, y: float) -> str:
    return f"{(x - X0) * UNIT:.2f},{(y - Y0) * UNIT:.2f}"


def bar(x1: float, x2: float, y: float, h: float) -> str:
    r = h / 2 * UNIT
    return (f"M{p(x1 + h / 2, y)} H{(x2 - h / 2 - X0) * UNIT:.2f} A{r:.2f},{r:.2f} 0 0 1 {p(x2 - h / 2, y + h)} "
            f"H{(x1 + h / 2 - X0) * UNIT:.2f} A{r:.2f},{r:.2f} 0 0 1 {p(x1 + h / 2, y)} Z")


CX, CY, R, STROKE = 9.0, 10.0, 6.2, 1.5
BARS = bar(1.5, 16.5, 11.2, 1.5) + " " + bar(5.5, 12.5, 14.0, 1.3)
R_U = R * UNIT
SUN = f"M{p(CX - R, CY)} A{R_U:.2f},{R_U:.2f} 0 0 1 {p(CX + R, CY)} Z"
RI, CAP = (R - STROKE) * UNIT, STROKE / 2 * UNIT
ARCH = (f"M{p(CX - R, CY)} A{R_U:.2f},{R_U:.2f} 0 0 1 {p(CX + R, CY)} "
        f"A{CAP:.2f},{CAP:.2f} 0 0 1 {p(CX + R - STROKE, CY)} "
        f"A{RI:.2f},{RI:.2f} 0 0 0 {p(CX - R + STROKE, CY)} "
        f"A{CAP:.2f},{CAP:.2f} 0 0 1 {p(CX - R, CY)} Z")

WEIGHTS = ["Ultralight", "Thin", "Light", "Regular", "Medium", "Semibold", "Bold", "Heavy", "Black"]
ROWS = {"S": 696.0, "M": 1126.0, "L": 1556.0}
COLUMN0, COLUMN_STEP = 500.0, 296.0


def svg(path: str, name: str) -> str:
    groups, margins = [], []
    for scale, base in ROWS.items():
        for i, weight in enumerate(WEIGHTS):
            x = COLUMN0 + i * COLUMN_STEP
            groups.append(f'  <g id="{weight}-{scale}" transform="matrix(1 0 0 1 {x:.2f} {base:.2f})">\n'
                          f'   <path d="{path}"/>\n  </g>')
            if (weight, scale) in (("Ultralight", "S"), ("Regular", "S"), ("Black", "S"), ("Regular", "M")):
                for side, mx in (("left", x), ("right", x + WIDTH)):
                    margins.append(f'  <line id="{side}-margin-{weight}-{scale}" x1="{mx:.2f}" x2="{mx:.2f}" '
                                   f'y1="{base - 95:.2f}" y2="{base + 24:.2f}" style="fill:none;stroke:#00AEEF;stroke-width:0.5;opacity:1.0;"/>')
    guides = []
    for scale, base in ROWS.items():
        guides.append(f'  <line id="Baseline-{scale}" x1="263" x2="3036" y1="{base:.2f}" y2="{base:.2f}" style="fill:none;stroke:#27AAE1;stroke-width:0.5;opacity:1.0;"/>')
        guides.append(f'  <line id="Capline-{scale}" x1="263" x2="3036" y1="{base - 70.46:.2f}" y2="{base - 70.46:.2f}" style="fill:none;stroke:#27AAE1;stroke-width:0.5;opacity:1.0;"/>')
    return f'''<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE svg PUBLIC "-//W3C//DTD SVG 1.1//EN" "http://www.w3.org/Graphics/SVG/1.1/DTD/svg11.dtd">
<svg version="1.1" xmlns="http://www.w3.org/2000/svg" xmlns:xlink="http://www.w3.org/1999/xlink" width="3300" height="2200">
 <!--glyph: "{name}", generated by apps/ios/tools/generate-control-symbols.py-->
 <g id="Notes">
  <rect height="2200" id="artboard" style="fill:white;opacity:1" width="3300" x="0" y="0"/>
  <text id="template-version" style="stroke:none;fill:black;font-family:sans-serif;font-size:13;" transform="matrix(1 0 0 1 2952 1933)">Template v.4.0</text>
  <text id="descriptive-name" style="stroke:none;fill:black;font-family:sans-serif;font-size:13;" transform="matrix(1 0 0 1 2865 1969)">{name}</text>
 </g>
 <g id="Guides">
{chr(10).join(guides)}
{chr(10).join(margins)}
 </g>
 <g id="Symbols">
{chr(10).join(groups)}
 </g>
</svg>
'''


CONTENTS = '''{
  "info" : {
    "author" : "xcode",
    "version" : 1
  },
  "properties" : {
    "symbol-rendering-intent" : "template"
  },
  "symbols" : [
    {
      "filename" : "%s.svg",
      "idiom" : "universal"
    }
  ]
}
'''

for name, path in (("tono.sun.on", SUN + " " + BARS), ("tono.sun.off", ARCH + " " + BARS)):
    folder = ASSETS / f"{name}.symbolset"
    folder.mkdir(parents=True, exist_ok=True)
    (folder / f"{name}.svg").write_text(svg(path, name))
    (folder / "Contents.json").write_text(CONTENTS % name)
    print(folder)
